"""``ayasee import-plan``: the ``import`` blocks of a unit's first adoption (issue #11).

Input is the ``show -json`` of a plan of the unit made **without** import blocks: every object the
code would create appears as a ``create``. For each planned create of a supported resource type,
a provider lookup lists the live objects that the resource would collide with, through the
provider's API with **read-only GET requests**, and the matching object's import ID is written as
an ``import { to = <address>, id = "<id>" }`` block. The output goes next to ``terragrunt.hcl``
(Terragrunt copies it into the working directory with the shared code), so each stage gets its own
IDs.

The rules, all fail closed:

- One live object matches: an import block. None: the object is new and stays a create.
- Two or more live objects match one address, or one live object matches two addresses: the
  address is reported as ambiguous and **nothing is written**. Resolve it by hand.
- An identifying attribute unknown at plan time, or a resource type with no lookup: reported as
  skipped; write that block by hand if the object exists.
- An API error, an unexpected response or an ID that is not a plain identifier: nothing is written.
- An existing output file is not overwritten without ``--force``.

Stdout lists each planned create with its outcome by address only; IDs appear only in the file.
The API token is read from the provider's own environment variable and never printed.

Lookups live in one module per provider (``cloudflare.py``) and register their resource types in
:data:`PROVIDERS`; adding a provider adds a module and one entry there.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol

from ayasee import cli
from ayasee.planjson import Action, PlanFormatError, load_plan

# A provider import ID is a few plain identifiers joined by "/"; anything else (quotes, "${",
# newlines) would be HCL injection in the written file, so it is refused.
_ID_PART = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")
_HEADER = """\
# Generated by `ayasee import-plan` from a plan of this unit and read-only lookups in the
# provider API. Review every block before you commit it: an import adopts the live object as it
# is, and the plan of the pull request shows any difference between it and the code as an update.
# Remove this file in a follow-up pull request once the objects are in state.
"""


class ImportPlanError(Exception):
    """Stop without writing anything: API error, unexpected response, unsafe ID."""


class Unmatchable(Exception):
    """This planned create cannot be looked up (an unknown attribute, an unsupported shape)."""


@dataclass(frozen=True)
class Planned:
    """A planned create: its address, type and the planned values known at plan time."""

    address: str
    type: str
    after: dict[str, Any] = field(repr=False)
    after_unknown: dict[str, Any] = field(repr=False)

    def known_str(self, attr: str) -> str:
        """The planned string value of ``attr``; :class:`Unmatchable` when unknown or absent."""
        if self.after_unknown.get(attr) is True:
            raise Unmatchable(f"{attr} is unknown at plan time")
        value = self.after.get(attr)
        if not isinstance(value, str) or not value:
            raise Unmatchable(f"{attr} is not set")
        return value


class Lookup(Protocol):
    def find(self, planned: Planned) -> list[str]:
        """Import IDs of the live objects ``planned`` would collide with."""
        ...

    def close(self) -> None: ...


@dataclass(frozen=True)
class Provider:
    types: frozenset[str]
    open: Callable[[], Lookup]


def _providers() -> dict[str, Provider]:
    from ayasee.importplan import cloudflare

    return {"cloudflare": Provider(cloudflare.TYPES, cloudflare.Cloudflare.from_env)}


PROVIDERS: Callable[[], dict[str, Provider]] = _providers


def check_id(import_id: str) -> str:
    """``import_id`` if every ``/``-separated part is a plain identifier, else an error."""
    if not all(_ID_PART.match(p) for p in import_id.split("/")):
        raise ImportPlanError("a lookup returned an ID that is not a plain identifier")
    return import_id


def planned_creates(plan_json: Path) -> list[Planned]:
    """Managed resources whose only planned action is create, in plan order."""
    out = []
    for rc in load_plan(plan_json):
        if rc.mode != "managed" or rc.actions != (Action.CREATE,):
            continue
        if not isinstance(rc.after, dict):
            raise PlanFormatError(f"{rc.address}: planned values are not an object")
        if any(c in rc.address for c in ("\n", "\r", "${", "%{")):
            raise PlanFormatError("a resource address holds characters not allowed here")
        unknown = rc.after_unknown if isinstance(rc.after_unknown, dict) else {}
        out.append(Planned(rc.address, rc.type, rc.after, unknown))
    return out


@dataclass
class Outcome:
    address: str
    status: str  # import | create | skip | ambiguous
    reason: str = ""
    import_id: str | None = field(default=None, repr=False)


def resolve(creates: list[Planned], providers: dict[str, Provider]) -> list[Outcome]:
    """Look every planned create up. Raises :class:`ImportPlanError` on any API failure."""
    by_type = {t: name for name, p in providers.items() for t in p.types}
    lookups: dict[str, Lookup] = {}
    outcomes: list[Outcome] = []
    try:
        for planned in creates:
            name = by_type.get(planned.type)
            if name is None:
                outcomes.append(
                    Outcome(planned.address, "skip", "no lookup for this resource type")
                )
                continue
            if name not in lookups:
                lookups[name] = providers[name].open()
            try:
                ids = lookups[name].find(planned)
            except Unmatchable as exc:
                outcomes.append(Outcome(planned.address, "skip", str(exc)))
                continue
            ids = sorted({check_id(i) for i in ids})
            if not ids:
                outcomes.append(
                    Outcome(planned.address, "create", "no live object matches; it stays a create")
                )
            elif len(ids) > 1:
                outcomes.append(
                    Outcome(planned.address, "ambiguous", f"{len(ids)} live objects match")
                )
            else:
                outcomes.append(Outcome(planned.address, "import", import_id=ids[0]))
    finally:
        for lookup in lookups.values():
            lookup.close()
    first: dict[str, Outcome] = {}
    for o in outcomes:
        if o.status != "import" or o.import_id is None:
            continue
        if o.import_id in first:
            other = first[o.import_id]
            for x, y in ((o, other), (other, o)):
                x.status = "ambiguous"
                x.reason = f"matches the same live object as {y.address}"
        else:
            first[o.import_id] = o
    return outcomes


def render(outcomes: list[Outcome]) -> str:
    blocks = [
        f'import {{\n  to = {o.address}\n  id = "{o.import_id}"\n}}\n'
        for o in outcomes
        if o.status == "import"
    ]
    return _HEADER + "\n" + "\n".join(blocks)


def _run(args: argparse.Namespace) -> int:
    out = Path(args.out)
    if out.exists() and not args.force:
        print(f"import-plan: {out} exists; pass --force to overwrite it", file=sys.stderr)
        return 1
    try:
        creates = planned_creates(Path(args.plan_json))
        outcomes = resolve(creates, PROVIDERS())
    except (PlanFormatError, OSError) as exc:
        print(f"import-plan: cannot read the plan: {exc}", file=sys.stderr)
        return 1
    except ImportPlanError as exc:
        print(f"import-plan: {exc}; nothing written", file=sys.stderr)
        return 1
    for o in outcomes:
        print(f"{o.status:<9} {o.address}" + (f": {o.reason}" if o.reason else ""))
    if any(o.status == "ambiguous" for o in outcomes):
        print(f"import-plan: ambiguous matches; {out} not written. Resolve them by hand.")
        return 1
    count = sum(o.status == "import" for o in outcomes)
    if not count:
        print("import-plan: nothing to import")
        return 0
    out.write_text(render(outcomes))
    print(f"import-plan: wrote {count} import block(s) to {out}")
    return 0


def _setup(parser: argparse.ArgumentParser) -> None:
    parser.description = "Write import blocks for live objects a unit's plan would create."
    parser.add_argument(
        "--plan-json", required=True, help="`tofu show -json` of a plan of the unit"
    )
    parser.add_argument("--out", default="imports.tf", help="output file (default: imports.tf)")
    parser.add_argument("--force", action="store_true", help="overwrite an existing output file")
    parser.set_defaults(handler=_run)


cli.register("import-plan", _setup)
