def test_every_resource_type_of_the_cloudflare_example_has_a_lookup():
    import re

    shared = Path(__file__).parent.parent / "examples" / "cloudflare-s3" / "shared"
    types = {
        m
        for tf in shared.glob("*/main.tf")
        for m in re.findall(r'^resource "([a-z0-9_]+)"', tf.read_text(), re.M)
    }
    assert types
    assert types <= cloudflare.TYPES


