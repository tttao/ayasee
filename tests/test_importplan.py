def _ok(result, page=1, total_pages=1):
    body = {"success": True, "errors": [], "messages": [], "result": result}
    if isinstance(result, list):
        body["result_info"] = {"page": page, "per_page": 100, "total_pages": total_pages}
    return httpx.Response(200, json=body)


def _dns_side_effect(request):
    name = request.url.params.get("name.exact")
    records = {
        "app.example.com": [
            {"id": "rec-app", "name": "app.example.com", "type": "CNAME"},
        ],
        "new.example.com": [],
    }
    return _ok(records[name])


def _mock_estate(*, apps=None, policies=None, dns=_dns_side_effect):
    respx.get(ZONE_URL).mock(return_value=_ok({"id": ZONE, "name": "example.com"}))
    respx.get(DNS).mock(side_effect=dns)
    respx.get(TUNNEL_CFG).mock(
        return_value=_ok({"tunnel_id": TUNNEL, "config": {"ingress": []}, "source": "cloudflare"})
    )
    respx.get(APPS).mock(
        return_value=_ok(
            apps
            if apps is not None
            else [
                {"id": "app-other", "domain": "other.example.com", "type": "ssh"},
                {"id": "app-ssh", "domain": "SSH.example.com", "type": "ssh"},
            ]
        )
    )
    respx.get(POLICIES).mock(
        return_value=_ok(
            policies
            if policies is not None
            else [
                {"id": "pol-ssh", "name": "SSH to the host"},
                {"id": "pol-x", "name": "SSH to the host (old)"},
            ]
        )
    )


